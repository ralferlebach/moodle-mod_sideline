namespace mod_sideline\local\service;

use mod_sideline\local\ai\persona_registry;
use mod_sideline\local\model\recommendation;

/**
 * Turns recommendations into localised plain-text message blocks (P-07, P-08).
 *
 * The output carries no HTML at all: text is plain and the front end renders it as text. Action
 * URLs are resolved here from the course module, after a fresh visibility and availability check
 * (P-04); the client never supplies an id that is trusted.
 *
 * @package    mod_sideline
 * @copyright  2026 Ralf Erlebach
 * @license    http://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
class message_composer {
    /** @var string Commentary source: generated by the AI provider. */
    public const SOURCE_AI = 'ai';
    /** @var string Commentary source: localised template text. */
    public const SOURCE_TEMPLATE = 'template';
    /** @var string Commentary source: the safe generic text. */
    public const SOURCE_GENERIC = 'generic';

    /**
     * Compose template-based commentary.
     *
     * @param recommendation[] $recommendations Ordered, main message first.
     * @param \cm_info[] $cms Observed activities, for URL resolution.
     * @param string $persona Persona key.
     * @param string $lang Language code of the user.
     * @return array The commentary structure, see commentary_cache.
     */
    public function compose(array $recommendations, array $cms, string $persona, string $lang): array {
        if (!persona_registry::is_valid($persona)) {
            $persona = persona_registry::DEFAULT_KEY;
        }
        $sm = get_string_manager();
        $lang = $sm->translation_exists($lang) || $lang === 'en' ? $lang : 'en';

        $blocks = [];
        foreach ($recommendations as $index => $rec) {
            $a = $this->template_args($rec, $lang);
            if (!empty($rec->facts['templates'])) {
                $text = $this->custom_text($rec->facts['templates'], $a, $lang);
            } else {
                $stringid = 'tpl_' . $rec->key;
                if (!$sm->string_exists($stringid, 'mod_sideline')) {
                    continue;
                }
                $text = $sm->get_string($stringid, 'mod_sideline', $a, $lang);
            }
            if ($text === '') {
                continue;
            }
            // The persona opener colours only the main message.
            if ($index === 0) {
                $text = trim(persona_registry::opener($persona, $lang) . ' ' . $text);
            }
            $block = ['key' => $rec->key, 'text' => $text];
            $action = $this->action_for($rec, $cms, $lang);
            if ($action) {
                $block['action'] = $action;
            }
            $blocks[] = $block;
        }

        $source = self::SOURCE_TEMPLATE;
        if (!$blocks) {
            $source = self::SOURCE_GENERIC;
            $blocks[] = ['key' => 'generic', 'text' => $sm->get_string('tpl_generic', 'mod_sideline', null, $lang)];
        }

        return [
            'version' => 1,
            'locale' => $lang,
            'persona' => $persona,
            'source' => $source,
            'blocks' => $blocks,
        ];
    }

    /**
     * Compose commentary from texts that were produced elsewhere, for example by the AI gateway.
     *
     * The text of each block comes from the caller. Everything that carries authority, namely the
     * block key and the action link, is still derived here from the recommendation.
     *
     * @param recommendation[] $recommendations Ordered recommendations.
     * @param \cm_info[] $cms Observed activities, for URL resolution.
     * @param string $persona Persona key.
     * @param string $lang Language code.
     * @param string[] $texts Final text per recommendation key.
     * @param string $source Source label for the commentary.
     * @return array
     */
    public function with_texts(
        array $recommendations,
        array $cms,
        string $persona,
        string $lang,
        array $texts,
        string $source,
    ): array {
        $blocks = [];
        foreach ($recommendations as $rec) {
            if (!isset($texts[$rec->key])) {
                continue;
            }
            $block = ['key' => $rec->key, 'text' => $texts[$rec->key]];
            $action = $this->action_for($rec, $cms, $lang);
            if ($action) {
                $block['action'] = $action;
            }
            $blocks[] = $block;
        }
        return [
            'version' => 1,
            'locale' => $lang,
            'persona' => $persona,
            'source' => $source,
            'blocks' => $blocks,
        ];
    }

    /**
     * The safe generic commentary used when everything else failed (P-08, last step).
     *
     * @param string $persona Persona key.
     * @param string $lang Language code.
     * @return array
     */
    public function generic(string $persona, string $lang): array {
        $sm = get_string_manager();
        $lang = $sm->translation_exists($lang) || $lang === 'en' ? $lang : 'en';
        return [
            'version' => 1,
            'locale' => $lang,
            'persona' => $persona,
            'source' => self::SOURCE_GENERIC,
            'blocks' => [['key' => 'generic', 'text' => $sm->get_string('tpl_generic', 'mod_sideline', null, $lang)]],
        ];
    }

    /**
     * Typed, localised template variables. Dates are formatted here, for the user's own time zone.
     *
     * @param recommendation $rec Recommendation.
     * @param string $lang Language code.
     * @return \stdClass
     */
    private function template_args(recommendation $rec, string $lang): \stdClass {
        $a = new \stdClass();
        $a->label = (string) ($rec->facts['label'] ?? '');
        $a->nextlabel = (string) ($rec->facts['nextlabel'] ?? '');
        $a->done = (int) ($rec->facts['done'] ?? 0);
        $a->total = (int) ($rec->facts['total'] ?? 0);
        $format = get_string_manager()->get_string('strftimedatetimeshort', 'langconfig', null, $lang);
        $a->deadline = isset($rec->facts['deadline']) ? userdate((int) $rec->facts['deadline'], $format) : '';
        $a->opensat = isset($rec->facts['opensat']) ? userdate((int) $rec->facts['opensat'], $format) : '';
        $a->count = (int) ($rec->facts['count'] ?? 0);
        $a->group = (string) ($rec->facts['group'] ?? '');
        $a->names = implode(', ', array_map('strval', (array) ($rec->facts['names'] ?? [])));
        return $a;
    }

    /**
     * Render a custom rule template in the user's language, falling back to English, then any.
     *
     * @param array $templates Language code to template text.
     * @param \stdClass $a Template arguments.
     * @param string $lang Language code.
     * @return string Plain text.
     */
    private function custom_text(array $templates, \stdClass $a, string $lang): string {
        $template = $templates[$lang] ?? $templates['en'] ?? reset($templates);
        if (!is_string($template)) {
            return '';
        }
        $text = strtr($template, [
            '{label}' => $a->label,
            '{deadline}' => $a->deadline,
            '{done}' => (string) $a->done,
            '{total}' => (string) $a->total,
        ]);
        return trim(clean_param($text, PARAM_NOTAGS));
    }

    /**
     * Resolve the action of a recommendation to a link, after re-checking access.
     *
     * @param recommendation $rec Recommendation.
     * @param \cm_info[] $cms Observed activities.
     * @param string $lang Language code.
     * @return array|null Label and URL, or null when no safe action exists.
     */
    private function action_for(recommendation $rec, array $cms, string $lang): ?array {
        if ($rec->actiontype !== recommendation::ACTION_OPEN || !$rec->targetcmid) {
            return null;
        }
        $cm = $cms[$rec->targetcmid] ?? null;
        if (!$cm || !$cm->uservisible || !$cm->available || !$cm->url) {
            return null;
        }
        return [
            'label' => get_string_manager()->get_string('action_open', 'mod_sideline', null, $lang),
            'url' => $cm->url->out(false),
            'cmid' => (int) $cm->id,
        ];
    }

    /**
     * Final check right before delivery: drop every action whose target is not reachable by this user now.
     *
     * Cached commentary may be older than a change of role, group or visibility, so links are never
     * trusted from the cache (P-04, P0-01).
     *
     * @param array $commentary Commentary structure, from the cache or freshly composed.
     * @param \cm_info[] $cms Activities currently observable for the user.
     * @return array The commentary without unsafe actions.
     */
    public function sanitize(array $commentary, array $cms): array {
        foreach ($commentary['blocks'] ?? [] as $i => $block) {
            if (empty($block['action'])) {
                continue;
            }
            $cm = $cms[$block['action']['cmid'] ?? 0] ?? null;
            if (!$cm || !$cm->uservisible || !$cm->available) {
                unset($commentary['blocks'][$i]['action']);
            }
        }
        return $commentary;
    }
}
